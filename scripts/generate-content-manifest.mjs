// Build-time generator for the Studio content manifest. Sanity Studio runs in
// the browser and can't read the git content tree, so it can't tell which
// chapters still lack Scene art (the beats live in git, the art lives in
// Sanity). This emits the git-side beat ids into a plain TS module the Studio
// bundle can import, powering the per-chapter "Scene art" coverage panes in
// `src/sanity/structure.ts`. Runs at predev/prebuild alongside
// `copy-content-media.mjs`; the output is committed so tsc/CI/build work
// without a prior generator run, and regenerated here to stay current.
import fs from 'node:fs';
import path from 'node:path';
import fg from 'fast-glob';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'src', 'sanity', 'content-manifest.ts');

/** Reading beat ids = the chapter filenames (no extension), the same value a
 *  Scene's `beatRef` must carry. Sorted so the manifest is deterministic. */
function readingBeats() {
  return fg
    .sync('src/content/reading/*.{md,mdx}', { cwd: ROOT })
    .map((f) => path.basename(f).replace(/\.mdx?$/, ''))
    .sort();
}

const beats = readingBeats();

// Emit oxfmt's canonical single-quoted single-line array form directly (the file
// is committed and checked by `oxfmt --check` in CI). If the list ever grows
// past oxfmt's line width it would want a multiline wrap — CI's format gate
// flags that loudly, so it's a visible prompt to revisit, not a silent trap.
const arr = beats.map((b) => `'${b}'`).join(', ');
const body = `// GENERATED by scripts/generate-content-manifest.mjs — do not edit by hand.
// Git-side content ids the Sanity Studio bundle needs but can't read from disk.
// Regenerated at predev/prebuild; committed so builds work without a prior run.

/** Reading chapter ids (a Scene's \`beatRef\` for \`beat: 'reading'\`). */
export const READING_BEATS: readonly string[] = [${arr}];
`;

fs.writeFileSync(OUT, body);
console.log(
  `[content-manifest] wrote ${beats.length} reading beat(s) → ${path.relative(ROOT, OUT)}`,
);
